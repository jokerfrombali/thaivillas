"""Split the compressed media tree into GitHub Pages repos of <= LIMIT bytes each.

    python shard_media.py <media-root> <repos-dir> <map.json> [--limit-mb 900] [--owner jokerfrombali] [--prefix thaivillas-media-]

<media-root>/<source>/<slug>/NN.webp  ->  <repos-dir>/<prefix>NN/<source>/<slug>/NN.webp (hard links)
Writes <map.json>: {"<source>/<slug>": "https://<owner>.github.io/<prefix>NN"}.
A listing never spans two repos. Existing assignments in <map.json> are kept, so re-running after
new listings only appends to the last repo (or opens a new one).
"""
import argparse
import json
import os
from pathlib import Path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("media_root")
    ap.add_argument("repos_dir")
    ap.add_argument("map_json")
    ap.add_argument("--limit-mb", type=int, default=900)
    ap.add_argument("--owner", default="jokerfrombali")
    ap.add_argument("--prefix", default="thaivillas-media-")
    a = ap.parse_args()
    limit = a.limit_mb * 1024 * 1024
    root, repos = Path(a.media_root), Path(a.repos_dir)
    mp = json.loads(Path(a.map_json).read_text()) if Path(a.map_json).exists() else {}
    url = lambda n: f"https://{a.owner}.github.io/{a.prefix}{n:02d}"
    used = {}
    listings = []
    for src in sorted(p for p in root.iterdir() if p.is_dir()):
        for d in sorted(p for p in src.iterdir() if p.is_dir()):
            files = sorted(d.glob("*.webp"))
            if files:
                listings.append((f"{src.name}/{d.name}", files, sum(f.stat().st_size for f in files)))
    # sizes of already-assigned listings
    for key, files, size in listings:
        if key in mp:
            n = int(mp[key].rsplit("-", 1)[1])
            used[n] = used.get(n, 0) + size
    cur = max(used) if used else 1
    for key, files, size in listings:
        if key not in mp:
            if used.get(cur, 0) + size > limit:
                cur += 1
            mp[key] = url(cur)
            used[cur] = used.get(cur, 0) + size
        n = int(mp[key].rsplit("-", 1)[1])
        dst = repos / f"{a.prefix}{n:02d}" / key
        dst.mkdir(parents=True, exist_ok=True)
        for f in files:
            t = dst / f.name
            if not t.exists():
                os.link(f, t)
    for n in used:
        r = repos / f"{a.prefix}{n:02d}"
        (r / ".nojekyll").write_text("")
        (r / "README.md").write_text(
            f"# {a.prefix}{n:02d}\n\nPhotos for the Thai Villas site (part {n:02d}), served by GitHub Pages at {url(n)}/.\n\n"
            "Layout: `<source>/<listing-slug>/NN.webp` — source `gyp` = getyourphuket.com, `ind` = indreamsphuket.\n"
            "Which listing lives in which repo: `data/media-map.json` in the thaivillas repo.\n"
            "Generated by `tools/phuket-importer/shard_media.py`; do not edit by hand.\n")
        (r / "index.html").write_text(f"<!doctype html><meta charset=utf-8><title>{a.prefix}{n:02d}</title><p>Thai Villas photo storage, part {n:02d}.")
    Path(a.map_json).write_text(json.dumps(dict(sorted(mp.items())), indent=0))
    for n in sorted(used):
        print(f"{a.prefix}{n:02d}: {used[n] / 1024 / 1024:.0f} MB")


if __name__ == "__main__":
    main()
